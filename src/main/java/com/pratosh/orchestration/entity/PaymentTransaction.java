package com.pratosh.orchestration.entity;

import jakarta.persistence.*;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Represents a payment transaction handled by the payment
 * orchestration platform.
 */
@Entity
@Table(
        name = "payment_transactions",
        uniqueConstraints = {
                @UniqueConstraint(
                        name = "uk_transaction_reference",
                        columnNames = "transaction_reference"
                ),
                @UniqueConstraint(
                        name = "uk_transaction_merchant_order",
                        columnNames = "merchant_order_id"
                )
        },
        indexes = {
                @Index(
                        name = "idx_transaction_status",
                        columnList = "status"
                ),
                @Index(
                        name = "idx_transaction_created_at",
                        columnList = "created_at"
                ),
                @Index(
                        name = "idx_transaction_merchant_order",
                        columnList = "merchant_order_id"
                )
        }
)
public class PaymentTransaction {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Unique reference generated by our platform.
     */
    @Column(
            name = "transaction_reference",
            nullable = false,
            unique = true,
            length = 100
    )
    private String transactionReference;

    /**
     * Order reference provided by the merchant.
     *
     * This field is unique in the current data model.
     * When merchant accounts are introduced, uniqueness should
     * generally be enforced per merchant.
     */
    @Column(
            name = "merchant_order_id",
            nullable = false,
            length = 100
    )
    private String merchantOrderId;

    /**
     * Payment amount.
     * BigDecimal avoids floating-point rounding errors.
     */
    @Column(
            name = "amount",
            nullable = false,
            precision = 19,
            scale = 4
    )
    private BigDecimal amount;

    /**
     * ISO currency code, for example INR or USD.
     */
    @Column(
            name = "currency",
            nullable = false,
            length = 3
    )
    private String currency;

    /**
     * Payment method selected for the transaction.
     */
    @Enumerated(EnumType.STRING)
    @Column(
            name = "payment_method",
            nullable = false,
            length = 30
    )
    private PaymentMethod paymentMethod;

    /**
     * Current transaction lifecycle status.
     */
    @Enumerated(EnumType.STRING)
    @Column(
            name = "status",
            nullable = false,
            length = 30
    )
    private PaymentTransactionStatus status;

    /**
     * Payment provider selected by the orchestrator.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "provider_id")
    private PaymentProvider provider;

    /**
     * Provider's transaction reference, populated after
     * the gateway returns one.
     */
    @Column(
            name = "provider_transaction_reference",
            length = 150
    )
    private String providerTransactionReference;

    /**
     * Number of processing attempts made so far.
     */
    @Column(name = "attempt_count", nullable = false)
    private int attemptCount = 0;

    /**
     * Caller-supplied Idempotency-Key. Repeating a create request with the
     * same key returns the original transaction instead of a new one.
     * NULL values are allowed and do not conflict with each other.
     */
    @Column(name = "idempotency_key", length = 100, unique = true)
    private String idempotencyKey;

    @Column(name = "created_at", nullable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    public PaymentTransaction() {
    }

    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();

        createdAt = now;
        updatedAt = now;

        if (status == null) {
            status = PaymentTransactionStatus.CREATED;
        }
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();
    }

    public Long getId() {
        return id;
    }

    public String getTransactionReference() {
        return transactionReference;
    }

    public void setTransactionReference(String transactionReference) {
        this.transactionReference = transactionReference;
    }

    public String getMerchantOrderId() {
        return merchantOrderId;
    }

    public void setMerchantOrderId(String merchantOrderId) {
        this.merchantOrderId = merchantOrderId;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public void setAmount(BigDecimal amount) {
        this.amount = amount;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }

    public PaymentMethod getPaymentMethod() {
        return paymentMethod;
    }

    public void setPaymentMethod(PaymentMethod paymentMethod) {
        this.paymentMethod = paymentMethod;
    }

    public PaymentTransactionStatus getStatus() {
        return status;
    }

    public void setStatus(PaymentTransactionStatus status) {
        this.status = status;
    }

    public PaymentProvider getProvider() {
        return provider;
    }

    public void setProvider(PaymentProvider provider) {
        this.provider = provider;
    }

    public String getProviderTransactionReference() {
        return providerTransactionReference;
    }

    public void setProviderTransactionReference(
            String providerTransactionReference) {
        this.providerTransactionReference =
                providerTransactionReference;
    }

    public int getAttemptCount() {
        return attemptCount;
    }

    public void setAttemptCount(int attemptCount) {
        this.attemptCount = attemptCount;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public String getIdempotencyKey() {
        return idempotencyKey;
    }

    public void setIdempotencyKey(String idempotencyKey) {
        this.idempotencyKey = idempotencyKey;
    }
}
